// Generates 365 days of activity data for yearly heatmap
export function generateActivityData(): ActivityDay[] {
  const days: ActivityDay[] = [];
  const today = new Date("2026-08-18");
  
  // Seeded pattern to simulate realistic activity
  for (let i = 364; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split("T")[0];
    
    const dayOfWeek = d.getDay(); // 0 is Sunday, 6 is Saturday
    const dayNum = i;
    
    let count = 0;
    let level: 0 | 1 | 2 | 3 | 4 = 0;
    
    // Create activity clusters (more on weekends and recent days)
    const isRecent = i < 30;
    const isMediumRecent = i >= 30 && i < 120;
    const isOld = i >= 120;
    
    const rand = Math.sin(dayNum * 12.9898 + (dayOfWeek * 78.233)) * 43758.5453;
    const pseudo = Math.abs(rand - Math.floor(rand));
    
    if (isRecent) {
      if (pseudo > 0.15) {
        count = Math.floor(pseudo * 8) + 1;
      }
    } else if (isMediumRecent) {
      if (pseudo > 0.35) {
        count = Math.floor(pseudo * 6) + 1;
      }
    } else if (isOld) {
      if (pseudo > 0.5) {
        count = Math.floor(pseudo * 5) + 1;
      }
    }
    
    if (count === 0) level = 0;
    else if (count <= 2) level = 1;
    else if (count <= 4) level = 2;
    else if (count <= 6) level = 3;
    else level = 4;
    
    days.push({ date: dateStr, count, level });
  }
  return days;
}
